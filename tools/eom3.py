#!/usr/bin/env python3
"""The rank-3 EOM, the foundation for a dynamically generated lambda_3.

John's construction: instead of guessing lambda_3 = f(gamma_1, lambda_2)
kinematically, let lambda_3 be generated by its own equation of motion starting
from a reference where it vanishes. Then lambda_3 is first order in the
interaction and Hamiltonian-dependent, which is what a relaxing closure needs.

  i d<a^pvx_qwy>/dt = <[H, a^pvx_qwy]>,  H = sum h a^r_s + (1/2) sum V a^rt_su

The one-body piece raises gamma_3; the two-body piece raises gamma_4. That is why
the construction only closes in the CUMULANT language: setting lambda_3 = lambda_4
= 0 makes gamma_4 reconstruct from gamma_1 and lambda_2, so the driving term is a
functional of 4-index data alone.

Derived with the machinery verified in tools/eom1.py and checked against explicit
Fock space before use.
"""
import sys
import numpy as np
sys.path.insert(0, ".")
sys.path.insert(0, "tools")
from qdiss.symbolic import mkno

M, N = 6, 3
dim = 1 << M


def bare_product(u1, l1, u2, l2):
    word = mkno.ops_of(u1, l1) + mkno.ops_of(u2, l2)
    out = []
    for s, deltas, cre, ann in mkno.normal_order(word):
        if len(cre) == len(ann):
            out.append((s, deltas, tuple(cre), tuple(reversed(ann))))
    return out


def commutator_expectation(u1, l1, u2, l2):
    terms = []
    for s, d, up, lo in bare_product(u1, l1, u2, l2):
        terms.append((s, d + ((("G", len(up), up, lo),) if up else ())))
    for s, d, up, lo in bare_product(u2, l2, u1, l1):
        terms.append((-s, d + ((("G", len(up), up, lo),) if up else ())))
    return mkno.collect(terms)


D3 = ("p", "v", "x"), ("q", "w", "y")
ONE3 = commutator_expectation(("r",), ("s",), D3[0], D3[1])
TWO3 = commutator_expectation(("r", "t"), ("s", "u"), D3[0], D3[1])


def summarize(label, terms):
    by = {}
    for s, f in terms:
        g = [r for n, r, u, l in f if n == "G"]
        k = g[0] if g else 0
        by[k] = by.get(k, 0) + 1
    print("%-26s %4d terms   (%s)"
          % (label, len(terms),
             ", ".join("gamma_%d x%d" % (k, v) for k, v in sorted(by.items()))))


summarize("<[a^r_s, a^pvx_qwy]>", ONE3)
summarize("<[a^rt_su, a^pvx_qwy]>", TWO3)
print()
print("one-body piece, all terms:")
for s, f in ONE3:
    parts = []
    for n, r, u, l in f:
        parts.append(("d" if n == "D" else "g") + str(r)
                     + "[" + "".join(u) + ";" + "".join(l) + "]")
    print("   %+d  %s" % (s, " ".join(parts)))
print()

# ---------- numerical verification against explicit Fock space ----------
rng = np.random.default_rng(41)
popc = np.array([bin(s).count("1") for s in range(dim)])
psi = np.where(popc == N, rng.normal(size=dim) + 1j * rng.normal(size=dim), 0.0)
psi = psi / np.linalg.norm(psi)


def ad(p, v):
    out = np.zeros_like(v); bit = 1 << p
    for s in np.nonzero(v)[0]:
        if s & bit: continue
        out[s | bit] += ((-1.0) ** bin(s & (bit - 1)).count("1")) * v[s]
    return out


def aa(p, v):
    out = np.zeros_like(v); bit = 1 << p
    for s in np.nonzero(v)[0]:
        if not (s & bit): continue
        out[s ^ bit] += ((-1.0) ** bin(s & (bit - 1)).count("1")) * v[s]
    return out


def apply_str(up, lo, v):
    for q in lo:
        v = aa(q, v)
    for p in reversed(up):
        v = ad(p, v)
    return v


def rdm_el(up, lo):
    return np.vdot(psi, apply_str(list(up), list(lo), psi))


def evaluate(terms, sub):
    tot = 0.0 + 0j
    for c, facs in terms:
        val = complex(c)
        for n, r, u, l in facs:
            iu = [sub[i] for i in u]
            il = [sub[i] for i in l]
            if n == "D":
                val *= 1.0 if iu[0] == il[0] else 0.0
            else:
                val *= rdm_el(iu, il)
            if val == 0:
                break
        tot += val
    return tot


def brute(u1, l1, u2, l2, sub):
    a = ([sub[i] for i in u1], [sub[i] for i in l1])
    b = ([sub[i] for i in u2], [sub[i] for i in l2])
    ab = apply_str(a[0], a[1], apply_str(b[0], b[1], psi))
    ba = apply_str(b[0], b[1], apply_str(a[0], a[1], psi))
    return np.vdot(psi, ab - ba)


labels = "pqrstuvwxy"
w1 = w2 = 0.0
for _ in range(150):
    sub = {k: int(rng.integers(M)) for k in labels}
    w1 = max(w1, abs(evaluate(ONE3, sub) - brute(("r",), ("s",), D3[0], D3[1], sub)))
    w2 = max(w2, abs(evaluate(TWO3, sub)
                     - brute(("r", "t"), ("s", "u"), D3[0], D3[1], sub)))
print("numerical check, M=%d N=%d, 150 random index tuples:" % (M, N))
print("  one-body : %.3e" % w1)
print("  two-body : %.3e" % w2)
print("  VERDICT:", "BOTH EXACT" if max(w1, w2) < 1e-12 else "MISMATCH")
