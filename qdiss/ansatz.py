"""Rank-general cumulant reconstructions: a hierarchy of ansatze for lambda_k.

SYMBOLS, all in the spin-orbital basis with M spin orbitals and N electrons.

    gamma_k[p_1..p_k, q_1..q_k] = <a+_p1 .. a+_pk a_qk .. a_q1>,  Tr gamma_k = N!/(N-k)!
    lambda_k                    = the k-cumulant of the MKNO generalized normal ordering,
                                  i.e. gamma_k minus every product of lower cumulants, the
                                  expansion generated by qdiss.symbolic.mkno.gamma_to_cumulants
    Tr_k T [p_1..p_{k-1}, q_1..q_{k-1}] = sum_y T[p_1..p_{k-1} y, q_1..q_{k-1} y]
                                  the partial trace over the last index of each group
    eta_1 = I - gamma_1         the hole 1-RDM
    E     = gamma_1 - I/2       the particle-hole imbalance
    anti(E, X)                  E contracted into every one of X's 2(k-1) slots and summed;
                                for a 4-slot X, sum_r E[p,r]X[rv,qw] + E[v,r]X[pr,qw]
                                              + X[pv,rw]E[r,q] + X[pv,qr]E[r,w]

THE ONE RIGOROUS ALGEBRAIC CONSTRAINT, order-general, verified at k = 2, 3, 4 in
docs/CLOSURE-CONDITIONS.md at 1.9e-16, 2.5e-16 and 8.6e-15:

    Tr_2 lambda_2 = anti(E, gamma_1) - gamma_1 gamma_1 = -(gamma_1 - gamma_1^2) = -gamma_1 eta_1
    Tr_3 lambda_3 = anti(E, lambda_2)
    Tr_4 lambda_4 = anti(E, lambda_3) + (9/2)(chainA - chainB)

Multiple traces are implied by the single trace and must not be imposed separately.

THE HIERARCHY. Levels are ordered by what information they consume. Every level is defined
identically at every rank k, so a statement proved at one rank is testable at the next.

    L0  "null"        lambda_k = 0.  Uses nothing. At k=2 this is exactly TDHF (3.9e-16).
    L0' "scaled"      lambda_k = 0, with the separable groups rescaled so that
                      Tr_k gamma_k = (N-k+1) gamma_{k-1} holds. Uses N and the trace of gamma_k.
                      Mueller et al. arXiv:2405.05093 Eq. 14 is a two-coefficient member of this
                      level at k=3 (measured, tools/ansatz_place_muller.py: it fits
                      a*S3 + b*S12 + 0*lambda_3 at 3.5e-16, so it carries NO 3-cumulant).
    L1  "trace"       lambda_k = the minimum-Frobenius-norm tensor with the exact partial trace
                      above. Uses the single-trace identity and nothing else. Linear in the
                      target, so Lipschitz with a fixed constant; contains no inverse of any
                      gamma_1-dependent operator. This module's `min_norm_trace`.
    L1' "scaled+trace" L0' with its trace channel replaced by L1. The Lackner Eq. 43/44/45
                      contraction repair of Mueller is a member: qdiss.gpu.trace_inverse is the
                      same object as `min_norm_trace` up to which particular solution is chosen.
    L2  "pt"          lambda_k from a level-shifted adiabatic stationarity condition in the
                      rank-k equation of motion. The first level that carries V.

REPRESENTATION. A rank-k antisymmetric tensor is stored by its independent components
A[I,J] = T[I+J] over SORTED k-tuples I, J, with the full tensor recovered by signed
antisymmetrisation. Frobenius norms differ by the constant (k!)^2, so minimising ||A|| and
minimising ||T|| are the same problem. This is the same Mat_k used for the positivity work,
which carries an extra k! : Mat_k(T)[I,J] = k! T[I+J].
"""
import itertools
import numpy as np
import scipy.sparse as sp

from qdiss.symbolic import mkno

_LETTERS_UP = "pvxzu"
_LETTERS_LO = "qwyts"


def tuples(M, k):
    """All sorted k-tuples of distinct spin-orbital labels, the index set of Mat_k."""
    return list(itertools.combinations(range(M), k))


def _perms(k):
    out = []
    for pi in itertools.permutations(range(k)):
        s = 1
        seq = list(pi)
        for i in range(k):
            for j in range(i + 1, k):
                if seq[i] > seq[j]:
                    s = -s
        out.append((pi, s))
    return out


def tensor_to_coord(T, M, k):
    """A[I,J] = T[I+J] over sorted k-tuples; discards the redundant permuted copies."""
    tup = tuples(M, k)
    idx = np.array(tup, dtype=int)
    n = len(tup)
    A = np.empty((n, n), dtype=complex)
    for a, I in enumerate(tup):
        A[a, :] = T[tuple(I) + tuple(idx.T)]
    return A


def coord_to_tensor(A, M, k):
    """The unique antisymmetric tensor whose sorted-tuple components are A."""
    tup = tuples(M, k)
    idx = np.array(tup, dtype=int)
    base = np.zeros((M,) * (2 * k), dtype=complex)
    for a, I in enumerate(tup):
        base[tuple(I) + tuple(idx.T)] = A[a, :]
    out = np.zeros_like(base)
    for pu, su in _perms(k):
        for pl, sl in _perms(k):
            out += (su * sl) * base.transpose(tuple(pu) + tuple(k + i for i in pl))
    return out


def trace_map(M, k):
    """Sparse matrix of Tr_k in sorted-tuple coordinates: vec(A_k) -> vec(S_{k-1}).

    S[I',J'] = sum_{y not in I', y not in J'} eps(I',y) eps(J',y) A[sort(I'+y), sort(J'+y)],
    with eps(I',y) = (-1)^#{i in I' : i > y}, the sign that sorts (I'_1..I'_{k-1}, y).
    """
    up, lo = tuples(M, k), tuples(M, k - 1)
    pos = {t: i for i, t in enumerate(up)}
    nu, nl = len(up), len(lo)
    rows, cols, vals = [], [], []
    for a, Ip in enumerate(lo):
        for b, Jp in enumerate(lo):
            r = a * nl + b
            for y in range(M):
                if y in Ip or y in Jp:
                    continue
                ei = (-1) ** sum(1 for i in Ip if i > y)
                ej = (-1) ** sum(1 for j in Jp if j > y)
                c = pos[tuple(sorted(Ip + (y,)))] * nu + pos[tuple(sorted(Jp + (y,)))]
                rows.append(r); cols.append(c); vals.append(float(ei * ej))
    return sp.csr_matrix((vals, (rows, cols)), shape=(nl * nl, nu * nu))


_TM_CACHE = {}
_GRAM_CACHE = {}


def _trace_gram(M, k):
    """(T, pseudo-inverse of T T^dag).

    T T^dag is SINGULAR when the k-tuple space is too small to reach every (k-1)-tuple target:
    at k = 3, M = 4 the map runs from C(4,3)^2 = 16 coordinates onto a C(4,2)^2 = 36 dimensional
    space, so most targets are unreachable and no exact partial-trace inverse exists. This is the
    same degeneracy as the (M-4) denominator in Lackner Eq. 43, which is exactly zero at M = 4.
    A pseudo-inverse is used, so min_norm_trace returns the least-squares solution; the caller
    must check trace_residual rather than assume the constraint was met.
    """
    if (M, k) not in _GRAM_CACHE:
        T = _TM_CACHE.setdefault((M, k), trace_map(M, k))
        G = (T @ T.T).toarray()
        _GRAM_CACHE[(M, k)] = (T, np.linalg.pinv(G, rcond=1e-10, hermitian=True))
    return _GRAM_CACHE[(M, k)]


def trace_rank_deficiency(M, k):
    """(dim of the (k-1)-tuple target space, rank of Tr_k). Equal means every target reachable."""
    T = _TM_CACHE.setdefault((M, k), trace_map(M, k))
    G = (T @ T.T).toarray()
    ev = np.linalg.eigvalsh(G)
    return G.shape[0], int((ev > 1e-10 * max(ev.max(), 1.0)).sum())


def min_norm_trace(S, M, k):
    """The minimum-Frobenius-norm rank-k antisymmetric tensor with Tr_k lambda_k = S.

    S is a full (k-1)-rank antisymmetric tensor. Returns a full rank-k tensor. The solution is
    T^dag (T T^dag)^{-1} S with T the fixed partial-trace map, so it is LINEAR in S with
    coefficients depending only on (M, k): no gamma_1-dependent inverse, hence Lipschitz.
    """
    T, Ginv = _trace_gram(M, k)
    s = tensor_to_coord(S, M, k - 1).reshape(-1)
    A = (T.T @ (Ginv @ s)).reshape(len(tuples(M, k)), -1)
    return coord_to_tensor(A, M, k)


def project_trace(L, M, k):
    """The orthogonal projection of lambda_k onto the row space of the partial-trace map.

    Measured in tools/ansatz_validate.py: min_norm_trace(Tr_k L) is orthogonal to
    L - min_norm_trace(Tr_k L) at 1e-14, so this IS that orthogonal projector, and the fraction
    of ||lambda_k||^2 it retains is exactly the fraction of the cumulant the single-trace
    identity determines.
    """
    sub = "".join(_LETTERS_UP[:k - 1]) + "z" + "".join(_LETTERS_LO[:k - 1]) + "z->" \
        + "".join(_LETTERS_UP[:k - 1]) + "".join(_LETTERS_LO[:k - 1])
    return min_norm_trace(np.einsum(sub, L), M, k)


def retrace(L, S, M, k):
    """Replace only the trace channel of a reconstruction, keeping everything orthogonal to it.

    Returns (I - P) L + min_norm_trace(S), which has partial trace exactly S and differs from L
    by the minimum possible amount. This is the order-general form of closures.trace_correct.
    """
    return L - project_trace(L, M, k) + min_norm_trace(S, M, k)


def trace_residual(L, S, k):
    """max |Tr_k L - S| for a full rank-k tensor L and rank-(k-1) target S."""
    sub = "".join(_LETTERS_UP[:k - 1]) + "z" + "".join(_LETTERS_LO[:k - 1]) + "z->" \
        + "".join(_LETTERS_UP[:k - 1]) + "".join(_LETTERS_LO[:k - 1])
    return float(np.abs(np.einsum(sub, L) - S).max())


# ---------------------------------------------------------------- trace targets

def wedge(a, b):
    return np.einsum("pq,vw->pvqw", a, b) - np.einsum("pw,vq->pvqw", a, b)


def anti(E, X, k):
    """E contracted into each of X's 2(k-1) slots, summed. X has 2(k-1) indices."""
    u, l = _LETTERS_UP[:k - 1], _LETTERS_LO[:k - 1]
    out = np.zeros_like(X)
    for i in range(k - 1):
        s = list(u + l)
        tgt = "".join(s)
        s[i] = "Z"
        out += np.einsum("%sZ,%s->%s" % (u[i], "".join(s), tgt), E, X)
        s = list(u + l)
        s[k - 1 + i] = "Z"
        out += np.einsum("%s,Z%s->%s" % ("".join(s), l[i], tgt), X, E)
    return out


_P3 = [(p, (-1) ** sum(1 for i in range(3) for j in range(i + 1, 3) if p[i] > p[j]))
       for p in itertools.permutations(range(3))]


def antisym3(T):
    """Full antisymmetriser over three upper and three lower indices: 36 signed terms over 36."""
    out = np.zeros_like(T)
    for pu, su in _P3:
        for pl, sl in _P3:
            out += (su * sl) * T.transpose(tuple(pu) + tuple(3 + i for i in pl))
    return out / 36.0


def anti3(E, X):
    """E contracted into each of the six slots of a rank-3 tensor, summed."""
    out = np.einsum("pr,rvxqwy->pvxqwy", E, X)
    out += np.einsum("vr,prxqwy->pvxqwy", E, X)
    out += np.einsum("xr,pvrqwy->pvxqwy", E, X)
    out += np.einsum("pvxrwy,rq->pvxqwy", X, E)
    out += np.einsum("pvxqry,rw->pvxqwy", X, E)
    out += np.einsum("pvxqwr,ry->pvxqwy", X, E)
    return out


def connected_basis(g1, l2, M):
    """Connected rank-3 structures: single contractions of two 2-cumulants.

    Each term joins the two lambda_2 factors through ONE summed index, optionally passing through
    gamma_1 or eta_1 = I - gamma_1, and is then antisymmetrised and pair-Hermitised; the anti(E)
    dressings contract E = gamma_1 - I/2 into the free slots. Because the two factors share an
    index, block-diagonality of lambda_2 forces all six external indices into one fragment, so
    every member has EXACTLY zero cross-fragment leak -- the extensivity that no wedge-based
    construction can have. Generated redundantly; the true span is 4-dimensional.
    """
    I = np.eye(M, dtype=complex)
    E = g1 - 0.5 * I
    out = []
    for nm, D in (("bare", I), ("g1", g1), ("eta", I - g1)):
        for tag, sub in (("chain", "pvqr,rs,sxwy->pvxqwy"), ("chainT", "prqw,rs,vxsy->pvxqwy")):
            X = antisym3(np.einsum(sub, l2, D, l2, optimize=True))
            X = 0.5 * (X + np.conj(X.transpose(3, 4, 5, 0, 1, 2)))
            out.append(("%s_%s" % (tag, nm), X))
            Y = anti3(E, X)
            out.append(("anti(E).%s_%s" % (tag, nm),
                        0.5 * (Y + np.conj(Y.transpose(3, 4, 5, 0, 1, 2)))))
    return out


def trace_target(k, g1, lower):
    """The exact value of Tr_k lambda_k. `lower` is lambda_{k-1} (= gamma_1 when k = 2)."""
    M = g1.shape[0]
    E = g1 - 0.5 * np.eye(M, dtype=complex)
    if k == 2:
        return -(g1 - g1 @ g1)
    if k == 3:
        return anti(E, lower, 3)
    raise ValueError("trace target implemented for k = 2, 3; k = 4 needs the chain terms")


# ---------------------------------------------------------------- MKNO separable groups

def _mkno_groups(k):
    """The cumulant expansion of gamma_k split into: terms with no lambda_k ('sep'),
    and the single fully connected term ('top'). Returns einsum-ready triples."""
    up, lo = tuple(_LETTERS_UP[:k]), tuple(_LETTERS_LO[:k])
    out_sub = "".join(up) + "".join(lo)
    all_t = [(s, ",".join("".join(u) + "".join(l) for n, r, u, l in f) + "->" + out_sub,
              [(n, r) for n, r, u, l in f])
             for s, f in mkno.gamma_to_cumulants(up, lo)]
    sep = [t for t in all_t if ("L", k) not in t[2]]
    return sep


_SEP_CACHE = {}


def separable(k, tab):
    """gamma_k with lambda_k set to zero: every MKNO term built from the lower cumulants.

    `tab` maps ("G",1) -> gamma_1 and ("L",j) -> lambda_j for 2 <= j <= k-1.
    """
    sep = _SEP_CACHE.setdefault(k, _mkno_groups(k))
    out = None
    for s, sub, keys in sep:
        piece = s * np.einsum(sub, *[tab[key] for key in keys], optimize=True)
        out = piece if out is None else out + piece
    return out


def cumulant(k, gk, tab):
    """lambda_k = gamma_k - separable(k, tab)."""
    return gk - separable(k, tab)


def separable_dot(k, tab, dtab):
    """d/dt of separable(k, tab) by the product rule over the MKNO term list.

    Each term is a product of factors; its rate is the sum over which factor carries the rate.
    `dtab` supplies the rate for each key of `tab`. Used to convert a moment rate into a cumulant
    rate: lambda_k-dot = gamma_k-dot - separable_dot(k, ...).
    """
    sep = _SEP_CACHE.setdefault(k, _mkno_groups(k))
    out = None
    for s, sub, keys in sep:
        for i in range(len(keys)):
            args = [dtab[key] if j == i else tab[key] for j, key in enumerate(keys)]
            piece = s * np.einsum(sub, *args, optimize=True)
            out = piece if out is None else out + piece
    return out


def _pow_dot(g1, dg1, a):
    """d/dt of gamma_1^a."""
    if a == 0:
        return np.zeros_like(g1)
    out = np.zeros_like(g1)
    for i in range(a):
        left = np.linalg.matrix_power(g1, i)
        right = np.linalg.matrix_power(g1, a - 1 - i)
        out = out + left @ dg1 @ right
    return out


def connected_basis_dot(g1, l2, dg1, dl2, M):
    """Rates of the connected_basis structures, by the product rule.

    Every wrapper in connected_basis -- antisym3, the pair-Hermitisation, anti3 -- is LINEAR, so it
    passes through the derivative unchanged; only the einsum factors and the gamma_1 powers need the
    product rule. Returned in the same order as connected_basis, so the two zip.
    """
    I = np.eye(M, dtype=complex)
    E = g1 - 0.5 * I
    dE = dg1
    out = []
    for a, (D, dD) in enumerate(((I, np.zeros_like(g1)), (g1, dg1), (I - g1, -dg1))):
        for tag, sub in (("chain", "pvqr,rs,sxwy->pvxqwy"), ("chainT", "prqw,rs,vxsy->pvxqwy")):
            dX = (np.einsum(sub, dl2, D, l2, optimize=True)
                  + np.einsum(sub, l2, dD, l2, optimize=True)
                  + np.einsum(sub, l2, D, dl2, optimize=True))
            dX = antisym3(dX)
            dX = 0.5 * (dX + np.conj(dX.transpose(3, 4, 5, 0, 1, 2)))
            X = antisym3(np.einsum(sub, l2, D, l2, optimize=True))
            X = 0.5 * (X + np.conj(X.transpose(3, 4, 5, 0, 1, 2)))
            out.append(dX)
            dY = anti3(dE, X) + anti3(E, dX)
            out.append(0.5 * (dY + np.conj(dY.transpose(3, 4, 5, 0, 1, 2))))
    return out
